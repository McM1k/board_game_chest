def write(side, w, h):
    from PIL import Image, ImageDraw
    import numpy as np
    m = Image.new('L', (w, h), 0)
    d = ImageDraw.Draw(m)
    for poly in islands[side]:
        d.line(poly + [poly[0]], fill=1, width=5)
    lines = np.load(f'l{side}.png.npy')
    inside = Image.new('L', (w, h), 0)
    di = ImageDraw.Draw(inside)
    for poly in islands[side]:
        di.polygon(poly, fill=1)
    inside = np.asarray(inside).astype(bool)
    # keep white lines inside the islands only, plus the hand-drawn coasts
    out = (lines & inside) | np.asarray(m).astype(bool)
    np.save(f'l{side}i.npy', out)
